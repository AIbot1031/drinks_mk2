import fs from 'node:fs/promises';
import {isDeepStrictEqual} from 'node:util';
import {gzipSync} from 'node:zlib';
import {execFileSync} from 'node:child_process';
// Share constant pending fields instead of repeating them in every menu row.
// The public/auditable catalog stays intact; runtime expansion is lossless.
const catalog=JSON.parse(await fs.readFile('data/catalog.json','utf8'));
const base=catalog.drinks.filter(d=>d.sourceKind!=='nidin');
const added=catalog.drinks.filter(d=>d.sourceKind==='nidin');
const template={},columns={},pools={};
for(const key of Object.keys(added[0])){
 if(added.every(d=>isDeepStrictEqual(d[key],added[0][key])))template[key]=added[0][key];
 else {
  const values=added.map(d=>d[key]),unique=new Map();
  if(typeof values[0]==='string'||Array.isArray(values[0])){
   for(const value of values){const signature=JSON.stringify(value);if(!unique.has(signature))unique.set(signature,value);}
  }
  if(unique.size&&unique.size<values.length*.8){
   pools[key]=[...unique.values()];const ids=new Map([...unique.keys()].map((value,i)=>[value,i]));
   columns[key]=values.map(value=>ids.get(JSON.stringify(value)));
  }else columns[key]=values;
 }
}
const {drinks,...meta}=catalog;
const packed={meta:{...meta,totalProducts:new Set(drinks.map(d=>JSON.stringify([d.brand,d.name]))).size},base,template,columns,pools};
const expanded=columns.id.map((_,i)=>({...template,...Object.fromEntries(Object.entries(columns).map(([key,values])=>[key,pools[key]?pools[key][values[i]]:values[i]]))}));
if(!isDeepStrictEqual([...base,...expanded],drinks))throw Error('Packed catalog must preserve every source fact');
await fs.writeFile('data/catalog-runtime.json',JSON.stringify(packed)+'\n');
await fs.writeFile('data/catalog-runtime.bin',gzipSync(JSON.stringify(packed)));
const fields=Object.keys(columns).map(key=>`${JSON.stringify(key)}:`+(pools[key]?`packed.pools[${JSON.stringify(key)}][packed.columns[${JSON.stringify(key)}][i]]`:`packed.columns[${JSON.stringify(key)}][i]`)).join(',');
await fs.writeFile('worker/catalog.ts',`// Generated by scripts/build_catalog_runtime.mjs; lossless shared pending fields.\nimport bytes from '../data/catalog-runtime.bin';\nimport {gunzipSync} from 'node:zlib';\nimport type shape from '../data/catalog-runtime.json';\nimport type {Drink} from './types';\nconst packed:typeof shape=JSON.parse(gunzipSync(new Uint8Array(bytes)).toString('utf8'));\nconst drinks:Drink[]=[...packed.base,...packed.columns.id.map((_,i)=>({...packed.template,${fields}}))];\nexport default {...packed.meta,drinks};\n`);
console.log(`Runtime catalog verified: ${base.length} original + ${expanded.length} menu variants`);
const directory=JSON.parse(await fs.readFile('data/nidin-directory.json','utf8'));
const nameIds=new Map(),names=[],menuIds=new Map(),menus=[];
const {stores,...directoryMeta}=directory;
const storeRows=stores.map(({menuNames,...rest})=>{
 if(menuNames===undefined)return {...rest,menuNames:null};
 const ids=menuNames.map(name=>{if(!nameIds.has(name)){nameIds.set(name,names.length);names.push(name);}return nameIds.get(name);});
 const signature=JSON.stringify(ids);
 if(!menuIds.has(signature)){menuIds.set(signature,menus.length);menus.push(ids);}
 return {...rest,menuNames:menuIds.get(signature)};
});
const directoryPacked={meta:directoryMeta,names,menus,stores:storeRows};
const decodedMenus=menus.map(ids=>ids.map(id=>names[id]));
const rebuiltStores=storeRows.map(({menuNames,...rest})=>menuNames===null?rest:{...rest,menuNames:decodedMenus[menuNames]});
if(!isDeepStrictEqual({...directoryMeta,stores:rebuiltStores},directory))throw Error('Packed directory must preserve all branch/menu facts');
await fs.writeFile('data/directory-runtime.json',JSON.stringify(directoryPacked)+'\n');
await fs.writeFile('data/directory-runtime.bin',gzipSync(JSON.stringify(directoryPacked)));
console.log(`Runtime directory verified: ${stores.length} stores, ${names.length} shared menu names`);
execFileSync(process.execPath,['--import','tsx','scripts/build_lexical_index.ts'],{stdio:'inherit'});
