import fs from 'node:fs/promises';
import {isDeepStrictEqual} from 'node:util';
import {gzipSync} from 'node:zlib';
// Share constant pending fields instead of repeating them in every menu row.
// The public/auditable catalog stays intact; runtime expansion is lossless.
const catalog=JSON.parse(await fs.readFile('data/catalog.json','utf8'));
const base=catalog.drinks.filter(d=>d.sourceKind!=='nidin');
const added=catalog.drinks.filter(d=>d.sourceKind==='nidin');
const template={},columns={};
for(const key of Object.keys(added[0])){
 if(added.every(d=>isDeepStrictEqual(d[key],added[0][key])))template[key]=added[0][key];
 else columns[key]=added.map(d=>d[key]);
}
const {drinks,...meta}=catalog;
const packed={meta,base,template,columns};
const expanded=columns.id.map((_,i)=>({...template,...Object.fromEntries(Object.entries(columns).map(([key,values])=>[key,values[i]]))}));
if(!isDeepStrictEqual([...base,...expanded],drinks))throw Error('Packed catalog must preserve every source fact');
await fs.writeFile('data/catalog-runtime.json',JSON.stringify(packed)+'\n');
await fs.writeFile('data/catalog-runtime.bin',gzipSync(JSON.stringify(packed)));
const fields=Object.keys(columns).map(key=>`${JSON.stringify(key)}:packed.columns[${JSON.stringify(key)}][i]`).join(',');
await fs.writeFile('worker/catalog.ts',`// Generated by scripts/build_catalog_runtime.mjs; lossless shared pending fields.\nimport bytes from '../data/catalog-runtime.bin';\nimport {gunzipSync} from 'node:zlib';\nimport type shape from '../data/catalog-runtime.json';\nimport type {Drink} from './types';\nconst packed:typeof shape=JSON.parse(gunzipSync(new Uint8Array(bytes)).toString('utf8'));\nconst drinks:Drink[]=[...packed.base,...packed.columns.id.map((_,i)=>({...packed.template,${fields}}))];\nexport default {...packed.meta,drinks};\n`);
console.log(`Runtime catalog verified: ${base.length} original + ${expanded.length} menu variants`);
